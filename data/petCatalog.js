const slugify = (value) => value
  .normalize('NFD')
  .replace(/[\u0300-\u036f]/g, '')
  .toLowerCase()
  .replace(/đ/g, 'd')
  .replace(/[^a-z0-9]+/g, '_')
  .replace(/^_|_$/g, '');

const petCatalog = rawPets.map(([name, theme, rarity]) => {
  const stats = rarityStats[rarity];

  return {
    pet_key: slugify(name),
    name,
    theme,
    rarity,
    description: `${name} là một pet ${theme.toLowerCase()} đáng yêu.`,
    image_url: null,
    base_attack: stats.attack,
    base_defense: stats.defense,
    base_speed: stats.speed,
    weight: rarityWeights[rarity],
  };
});

